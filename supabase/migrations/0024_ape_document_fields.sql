-- =====================================================================
-- Migration 0024 : Πεδία που απαιτούν τα ΕΠΙΣΗΜΑ έγγραφα της Δ/νσης
--
-- Πηγή: εγκεκριμένοι ΑΠΕ, φύλλα ελέγχου επί έλαττον και αιτιολογικές
-- εκθέσεις πέντε έργων (Έμπωνα, Καλλιθέα, Κοσκινού, Ν. Ρόδου, Πυρκαγιές).
-- Χωρίς αυτά τα πεδία η αιτιολογική έκθεση και ο πίνακας του ΑΠΕ δεν
-- μπορούν να παραχθούν πλήρεις.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 24.1 ΑΝΑΘΕΣΗ ΚΑΙ ΝΟΜΙΜΟΠΟΙΗΣΗ ΤΗΣ ΣΥΜΒΑΣΗΣ
--
-- Το «Α. ΙΣΤΟΡΙΚΟ» κάθε αιτιολογικής έκθεσης ανοίγει με τη μορφή:
--   «Με την 960/22-12-2025 απόφαση της Δημοτικής Επιτροπής του Δήμου
--    Ρόδου που νομιμοποιήθηκε με το αρ. 4419/19-2-2026 έγγραφο της
--    Αποκεντρωμένης Διοίκησης Αιγαίου ...»
-- Ο αριθμός και η ημερομηνία τηρούνται ΧΩΡΙΣΤΑ ώστε να συντίθεται το
-- «960/22-12-2025» χωρίς να πληκτρολογείται ως ελεύθερο κείμενο.
-- ---------------------------------------------------------------------
alter table public.contracts
  add column if not exists award_body            text,
  add column if not exists award_decision_no     text,
  add column if not exists award_decision_date   date,
  add column if not exists legalization_doc_no   text,
  add column if not exists legalization_doc_date date,
  add column if not exists legalization_authority text;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'contracts_award_body_chk'
  ) then
    alter table public.contracts
      add constraint contracts_award_body_chk check (
        award_body is null or award_body in (
          'dimotiki_epitropi',    -- Δημοτική Επιτροπή (από ν. 5056/2023)
          'oikonomiki_epitropi',  -- Οικονομική Επιτροπή (προγενέστερα)
          'dimotiko_symvoulio',
          'dioikitiko_symvoulio',
          'allo'
        ));
  end if;
end $$;

comment on column public.contracts.award_body is
  'Το όργανο που ενέκρινε το πρακτικό και την ανάθεση. Μέχρι τον ν.5056/2023 '
  'ήταν η Οικονομική Επιτροπή· έκτοτε η Δημοτική Επιτροπή. Και τα δύο '
  'εμφανίζονται στα έργα μας, ανάλογα με το έτος ανάθεσης.';

comment on column public.contracts.legalization_doc_no is
  'Αριθμός εγγράφου της Αποκεντρωμένης Διοίκησης με το οποίο νομιμοποιήθηκε '
  'η απόφαση ανάθεσης (έλεγχος νομιμότητας, άρθρα 225-227 ν.3852/2010).';

-- ---------------------------------------------------------------------
-- 24.2 ΚΩΔΙΚΟΣ ΑΝΑΘΕΩΡΗΣΗΣ ΣΤΙΣ ΓΡΑΜΜΕΣ ΤΟΥ ΑΠΕ
--
-- Ο επίσημος πίνακας ΑΠΕ φέρει στήλη «Κωδικός Αναθεώρησης» (ΟΙΚ 2113,
-- ΥΔΡ 6068, ΟΔΟ-1123Α ...) δίπλα σε κάθε άρθρο. Ο πίνακας budget_items
-- τον έχει ήδη· ο ape_lines όχι, οπότε η πληροφορία χανόταν μόλις οι
-- γραμμές περνούσαν στον ΑΠΕ.
-- ---------------------------------------------------------------------
alter table public.ape_lines
  add column if not exists revision_code text,
  add column if not exists etep_code     text;

comment on column public.ape_lines.revision_code is
  'Κωδικός αναθεώρησης του άρθρου (π.χ. ΟΙΚ 2113). Εμφανίζεται σε δική του '
  'στήλη στον Ανακεφαλαιωτικό Πίνακα και θεμελιώνει τον υπολογισμό της '
  'αναθεώρησης τιμών.';

-- ---------------------------------------------------------------------
-- 24.3 ΛΟΓΙΣΤΙΚΟ ΛΑΘΟΣ ΣΤΟΝ ΑΠΕ
--
-- Στον πίνακα δαπάνης υπάρχει ξεχωριστή γραμμή «ΛΟΓΙΣΤΙΚΟ ΛΑΘΟΣ» μεταξύ
-- ΣΥΝΟΛΟΥ 2 και ΣΥΝΟΛΟΥ 3 (Κοσκινού: -0,01 €). Είναι η διαφορά
-- στρογγυλοποίησης που μεταφέρεται αυτούσια από τη σύμβαση και ΔΕΝ
-- εξαφανίζεται σιωπηλά.
-- ---------------------------------------------------------------------
alter table public.ape
  add column if not exists accounting_error numeric(14,2) not null default 0;

comment on column public.ape.accounting_error is
  'Λογιστικό λάθος: διαφορά στρογγυλοποίησης που μεταφέρεται από τη σύμβαση. '
  'Τηρείται ρητά ως δική της γραμμή, ώστε τα σύνολα του ΑΠΕ να συμφωνούν '
  'κατά λεπτό με τα συμβατικά.';

-- ---------------------------------------------------------------------
-- 24.4 ΕΡΓΑΣΙΕΣ ΤΟΥ ΑΡΘΡΟΥ 132
--
-- Οι υπερσυμβατικές εργασίες τηρούνται σε ΞΕΧΩΡΙΣΤΗ ενότητα του πίνακα
-- («ΕΡΓΑΣΙΕΣ ΣΥΜΦΩΝΑ ΜΕ ΤΟ ΑΡΘΡΟ 132 ΤΟΥ Ν.4412/16»), δεν καλύπτονται
-- από απρόβλεπτα και προσαυξάνουν τη σύμβαση με όριο 15% (άρθρο 132 §2).
-- ---------------------------------------------------------------------
alter table public.ape_lines
  add column if not exists is_article_132 boolean not null default false;

alter table public.ape
  add column if not exists article_132_value numeric(14,2) not null default 0;

comment on column public.ape_lines.is_article_132 is
  'Η γραμμή ανήκει στην ενότητα του άρθρου 132 (υπερσυμβατικές εργασίες). '
  'Δεν χρηματοδοτείται από απρόβλεπτα.';

comment on column public.ape.article_132_value is
  'Συνολική δαπάνη εργασιών άρθρου 132 (εργασίες + ΓΕ & ΟΕ), χωρίς ΦΠΑ.';

create index if not exists ape_lines_art132_idx
  on public.ape_lines (ape_id) where is_article_132;
