              'γνωμοδότηση του τεχνικού συμβουλίου (§17)· στη γενική ένσταση της §3 '
              'δεν τεκμαίρεται καμία αποδοχή, ούτε δημιουργεί τεκμήριο η παράλειψη '
              'απόψεων της §5 (§7).'
where code = 'S23_ENSTASEIS';

do $$
declare s public.workflow_stages%rowtype;
begin
  select * into s from public.workflow_stages where code = 'S23_ENSTASEIS';
  if not found then
    raise notice '0030: το στάδιο S23_ENSTASEIS δεν υπάρχει — καμία ενέργεια.';
    return;
  end if;
  if coalesce(array_length(s.extra_legal_refs, 1), 0) <> 8
     or s.purpose not like '%§15%' then
    raise exception '0030: το S23_ENSTASEIS δεν έχει τις παραπομπές του άρθρου 174.';
  end if;
end $$;
