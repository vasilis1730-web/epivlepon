            'συμβουλίου (§3). Για έργα Ο.Τ.Α. κάτω των ορίων αποφασίζει ο '
            'Συντονιστής της Αποκεντρωμένης Διοίκησης, κατόπιν γνώμης του τεχνικού '
            'συμβουλίου της οικείας Περιφέρειας, και μετά την έναρξη λειτουργίας '
            'της Α.Υ.Ε. Ο.Τ.Α. ο Επόπτης Ο.Τ.Α. (§12). Όλες οι προθεσμίες του '
            'άρθρου αναστέλλονται τον Αύγουστο (§15).',
  extra_legal_refs = array['N4412/174/1','N4412/174/3','N4412/174/5','N4412/174/11',
