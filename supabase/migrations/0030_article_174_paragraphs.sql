-- =====================================================================
-- 0030 — ΑΡΘΡΟ 174: ΟΙ ΠΑΡΑΓΡΑΦΟΙ ΠΟΥ ΕΛΕΙΠΑΝ
--
-- Το 0029 διόρθωσε την αφετηρία και το αποτέλεσμα της σιωπής. Το άρθρο
-- όμως δεν έχει μία προθεσμία — έχει τέσσερις, με διαφορετικό αποτέλεσμα
-- η καθεμία, και μια αναστολή που τις μετακινεί όλες:
--
--   §1α  15 ημέρες, ΑΝΑΤΡΕΠΤΙΚΗ, από την κοινοποίηση της πράξης, για την
--        άσκηση της ένστασης. Χωρίς επίδοση με δικαστικό επιμελητή ή
--        ηλεκτρονική αποστολή η ένσταση είναι ΑΠΑΡΑΔΕΚΤΗ — και επειδή κατά
--        το άρθρο 175 §2 η ένσταση είναι υποχρεωτική προδικασία, πέφτει και
--        η προσφυγή.
--   §5   15 ημέρες από την άσκηση για τη διαβίβαση απόψεων και φακέλου στο
--        τεχνικό συμβούλιο. Η παράλειψη είναι πειθαρχική παράβαση (άρθρο
--        141), αλλά κατά την §7 ΔΕΝ δημιουργεί τεκμήριο αποδοχής των λόγων
--        της ένστασης.
--   §3   60 ημέρες από την άσκηση για ΕΚΔΟΣΗ ΚΑΙ ΚΟΙΝΟΠΟΙΗΣΗ της απόφασης,
--        μετά από αιτιολογημένη γνώμη του τεχνικού συμβουλίου.
--   §17  30 ημέρες από τη ΓΝΩΜΟΔΟΤΗΣΗ του τεχνικού συμβουλίου, ΜΟΝΟ στην
--        ένσταση κατά απόφασης έκπτωσης. Εδώ και μόνο εδώ η παράλειψη
--        τεκμαίρεται ως σιωπηρή αποδοχή ΤΗΣ ΓΝΩΜΟΔΟΤΗΣΗΣ. Η έκπτωση δεν
--        οριστικοποιείται πριν από την απόφαση επί της ένστασης.
--
-- §11  Η άπρακτη πάροδος των 60 ημερών ανοίγει την προσφυγή του άρθρου 175,
--      και απόφαση που εκδίδεται ή κοινοποιείται ΑΡΓΟΤΕΡΑ δεν μεταθέτει την
--      έναρξη της προθεσμίας προσφυγής.
-- §12  Για έργα Δήμων, Περιφερειών και των νομικών τους προσώπων ΚΑΤΩ ΤΩΝ
--      ΟΡΙΩΝ αποφασίζει ο Συντονιστής της Αποκεντρωμένης Διοίκησης, κατόπιν
--      γνώμης του τεχνικού συμβουλίου της οικείας Περιφέρειας, και μετά την
--      έναρξη λειτουργίας της Α.Υ.Ε. Ο.Τ.Α. ο Επόπτης Ο.Τ.Α. ΔΕΝ αποφασίζει
--      η Προϊσταμένη Αρχή.
-- §15  Οι προθεσμίες ΟΛΟΥ του άρθρου αναστέλλονται κατά τον μήνα Αύγουστο.
--
-- ΤΙ ΔΕΝ ΚΑΝΕΙ ΑΥΤΟ ΤΟ MIGRATION. Το `approver` του σταδίου μένει
-- 'proistameni_arxi', γιατί το enum public.party_type δεν έχει τιμή για τον
-- Συντονιστή Αποκεντρωμένης Διοίκησης / Επόπτη Ο.Τ.Α. Η προσθήκη τιμής σε
-- enum δεν συνδυάζεται με χρήση της στην ίδια συναλλαγή, οπότε θέλει δικό
-- της migration· ως τότε η §12 καταγράφεται στο κείμενο του σταδίου.
-- Ομοίως η αναστολή του Αυγούστου δεν αλλάζει καμία υπολογισμένη ημερομηνία:
-- η app.compute_stage_due επιστρέφει ήδη null για αφετηρία 'ypovoli_eggrafou',
-- οπότε δεν υπάρχει ημερομηνία να ανασταλεί. Θα χρειαστεί όταν υλοποιηθεί
-- προθεσμία ανά εγγραφή ένστασης.
-- =====================================================================

