-- =====================================================================
-- 0029 — ΕΝΣΤΑΣΕΙΣ (ΑΡΘΡΟ 174): ΑΦΕΤΗΡΙΑ ΚΑΙ ΑΠΟΤΕΛΕΣΜΑ ΤΗΣ ΣΙΩΠΗΣ
--
-- Το κείμενο της διάταξης: «Το αρμόδιο αποφαινόμενο όργανο υποχρεούται να
-- εκδώσει και κοινοποιήσει την απόφασή του μέσα σε εξήντα (60) ημέρες από
-- την άσκηση της ένστασης, μετά από αιτιολογημένη γνώμη του τεχνικού
-- συμβουλίου.»
--
-- Το στάδιο S23_ENSTASEIS το απέδιδε λάθος σε δύο σημεία:
--
-- (α) ΑΦΕΤΗΡΙΑ. Είχε 'koinopoiisi_praxis', δηλαδή την κοινοποίηση της
--     ΠΡΟΣΒΑΛΛΟΜΕΝΗΣ πράξης. Η προθεσμία τρέχει από την ΑΣΚΗΣΗ της
--     ένστασης — άλλο γεγονός, αργότερα, και συχνά αρκετά αργότερα (η
--     ένσταση ασκείται εντός 15 ημερών από την κοινοποίηση). Και οι δύο
--     τιμές πέφτουν σήμερα στον ίδιο κλάδο της app.compute_stage_due, που
--     επιστρέφει null, οπότε η διόρθωση ΔΕΝ αλλάζει καμία υπολογισμένη
--     ημερομηνία· διορθώνει το τι δηλώνει το στάδιο, ώστε όποιος υλοποιήσει
--     αργότερα προθεσμία ανά εγγραφή να μετρήσει από το σωστό γεγονός.
--
-- (β) ΑΠΟΤΕΛΕΣΜΑ ΤΗΣ ΣΙΩΠΗΣ. Έλεγε «τεκμαίρεται σιωπηρή αποδοχή της
--     γνωμοδότησης». Η γνωμοδότηση του Τεχνικού Συμβουλίου ΠΡΟΗΓΕΙΤΑΙ της
--     απόφασης· δεν είναι το αντικείμενο της σιωπής. Ό,τι επέρχεται από την
--     άπρακτη πάροδο είναι η εξάντληση της ενδικοφανούς προδικασίας, που
--     ανοίγει τη δικαστική επίλυση του άρθρου 175. Η διάταξη δεν ορίζει
--     σιωπηρή αποδοχή ή απόρριψη, οπότε δεν δηλώνεται καμία.
--
-- Επίσης καταγράφεται ρητά ότι η 60ήμερη προθεσμία καλύπτει έκδοση ΚΑΙ
-- κοινοποίηση: απόφαση εκδοθείσα την 59η ημέρα και κοινοποιηθείσα την 65η
-- δεν την τηρεί.
--
-- Το 0013 ενημερώθηκε αναδρομικά για καθαρή εγκατάσταση. Αυτό το migration
-- υπάρχει για τις ΗΔΗ ΕΓΚΑΤΕΣΤΗΜΕΝΕΣ βάσεις, όπου το 0013 έχει τρέξει.
-- =====================================================================

update public.workflow_stages set
  purpose = 'Παραλαβή ένστασης εντός 15 ημερών από την κοινοποίηση της πράξης· '
            'εισήγηση και αιτιολογημένη γνώμη Τεχνικού Συμβουλίου· έκδοση ΚΑΙ '
            'κοινοποίηση της απόφασης εντός 60 ημερών από την άσκηση της ένστασης.',
  deadline_basis = 'ypovoli_eggrafou',
  tacit_effect = 'Άπρακτη πάροδος 60 ημερών από την άσκηση: εξαντλείται η '
                 'ενδικοφανής προδικασία και ανοίγει η δικαστική επίλυση του '
                 'άρθρου 175.'
where code = 'S23_ENSTASEIS';

do $$
declare s public.workflow_stages%rowtype;
begin
  select * into s from public.workflow_stages where code = 'S23_ENSTASEIS';
  if not found then
    raise notice '0029: το στάδιο S23_ENSTASEIS δεν υπάρχει — καμία ενέργεια.';
    return;
  end if;
  if s.deadline_basis is distinct from 'ypovoli_eggrafou'
     or s.deadline_days is distinct from 60
     or s.tacit_approval is not true then
    raise exception '0029: το S23_ENSTASEIS δεν έχει τη διόρθωση (basis=%, days=%, tacit=%)',
      s.deadline_basis, s.deadline_days, s.tacit_approval;
  end if;
end $$;
